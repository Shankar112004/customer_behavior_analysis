-- do subscribed customers spend more ? compare average spend and total revenue between subscribers and non subscibers.
select subscription_status ,
count(customer_id) as total_customer,
round(avg(purchase_amount),2) as average_spend,
round(sum(purchase_amount),2) as total_revenue
from customer 
group by subscription_status
order by total_revenue,average_spend desc ;

-- which 5 products have the highest percentage of purchase with discount applied ? 

select item_purchased ,
 round(100 * sum( discount_applied='Yes' ) /count(*),2)   as discount_rate 
from customer 
group by item_purchased
order by discount_rate desc
limit 5;

-- segment customers into new , returing , and loyal based on their total number 
-- of previous purchases , and show the count of each segment 


with customer_type as (
select customer_id, previous_purchases,
case
   when previous_purchases = 1  then 'New' 
   when previous_purchases between 2 and 10  then 'Returning'
   else 'loyal'
   end as customer_segment
from customer
)
select customer_segment , count(*)  as customer_number from customer_type 
group by customer_segment;


-- what are the top  3 most purchased products within each category ?

with item_counts as (
select category, item_purchased
,count(customer_id) as total_orders,
ROW_NUMBER() over( partition by category order by count(customer_id) desc ) as item_rank
from customer 
group by category , item_purchased
)
select item_rank, category, item_purchased, total_orders
from item_counts 
 where item_rank<=3;
 
 
 
